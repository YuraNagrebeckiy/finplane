const assert=require('node:assert/strict');
const {allocate,fundingEvents}=require('../ui/goal-funding.js');
const a={id:'washer',amount:40000,currency:'RUB',year:2026,month:'Ноябрь',day:10,status:'Запланировано'};
const b={id:'dishwasher',amount:60000,currency:'RUB',year:2026,month:'Декабрь',day:10,status:'Запланировано'};
const before=JSON.stringify([a,b]);
const initial=allocate([b,a],30000,100),next=allocate([b,a],50000,100);
assert.equal(JSON.stringify([a,b]),before);
assert.equal(next.allocations[0].goalId,'washer');assert.equal(next.allocations[0].allocatedCents,4000000);
assert.equal(next.allocations[0].ready,true);assert.equal(next.allocations[1].allocatedCents,1000000);assert.equal(next.allocations[1].ready,false);
assert.equal(next.allocations.reduce((sum,row)=>sum+row.allocatedCents,0)+next.unassignedCents,next.availableCents);
const event={type:'deposit',confirmed:true,actionId:'deposit-1'};
const effects=fundingEvents(initial,next,event,{});assert.equal(effects.length,2);assert.equal(effects[0].unlocked,true);assert.equal(effects[1].unlocked,false);
assert.equal(fundingEvents(initial,next,{...event,confirmed:false},{}).length,0);
assert.equal(fundingEvents(initial,next,{...event,type:'sync'},{}).length,0);
assert.equal(fundingEvents(next,next,event,{}).length,0);
assert.equal(fundingEvents(initial,next,event,Object.fromEntries(effects.map(x=>[x.key,true]))).length,0);
assert.equal(allocate([{...a,currency:'EUR',amount:100}],5000,100).allocations[0].progress,0.5);
assert.equal(allocate([{...a,currency:'EUR'}],5000,undefined).allocations[0].ready,false);
assert.equal(allocate([{...a,currency:'XYZ'}],5000,100).allocations[0].reason,'unsupported_currency');
assert.equal(allocate([{...a,amount:0}],5000,100).allocations[0].ready,false);
assert.equal(allocate([{...a,status:'Выполнено'},b],10000,100).allocations.length,1);
for(const value of [-1,NaN,Infinity,null])assert.throws(()=>allocate([a],value,100));
assert.throws(()=>allocate([a,a],100,100));
console.log('Goal funding conservation, readiness and event tests passed');
