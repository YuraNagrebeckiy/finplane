const assert = require("node:assert/strict");
const prepare = require("./BudgetIdentity.gs");
let sequence = 0;
const uuid = () => "generated-" + (++sequence);
const source = [{id:"a",date:"2026-11-05",custom:{keep:true},items:[{id:"i",amount:50,note:"keep"}]},{date:"2026-11-05",items:[{amount:50}]}];
const before = JSON.stringify(source);
const result = prepare(source, uuid);
assert.equal(JSON.stringify(source), before);
assert.equal(result[0].id, "a");
assert.equal(result[0].items[0].id, "i");
assert.equal(result[0].items[0].note, "keep");
assert.deepEqual(result[0].custom, {keep:true});
assert.notEqual(result[1].id, result[0].id);
assert.ok(result[1].items[0].id);
assert.deepEqual(prepare(result, uuid), result);
assert.throws(() => prepare([{id:"a"},{id:"a"}], uuid), /Duplicate operation/);
assert.throws(() => prepare([{id:"a",items:[{id:"i"},{id:"i"}]}], uuid), /Duplicate item/);
assert.throws(() => prepare([{items:{}}], uuid), /Invalid items/);
assert.throws(() => prepare({}, uuid), /array/);
assert.throws(() => prepare([null], uuid), /Invalid operation/);
assert.throws(() => prepare([{}], () => ""), /Cannot generate/);
assert.deepEqual(prepare([], uuid), []);
assert.equal(prepare([{id:0,items:[{id:0}]}], uuid)[0].id, 0);
console.log("Budget identity checks passed");
